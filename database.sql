
-- Base de datos: Pedidos familiares

-- Tabla principal de pedidos
CREATE TABLE IF NOT EXISTS public.pedidos_familia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creado_en TIMESTAMPTZ DEFAULT NOW(),
    nombre_responsable TEXT,
    pedidos JSONB
);

-- Tabla de integrantes de la familia
CREATE TABLE IF NOT EXISTS public.integrantes_familia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    pedido_id BIGINT REFERENCES public.pedidos_familia(id)
        ON DELETE CASCADE,
    creado_en TIMESTAMPTZ DEFAULT NOW()
);
